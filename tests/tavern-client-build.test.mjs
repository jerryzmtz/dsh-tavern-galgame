import {tmpdir as publicTmpdir} from 'node:os';
import {join as publicJoin} from 'node:path';
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { cp, copyFile, mkdir, mkdtemp, readFile, realpath, writeFile } from 'node:fs/promises'
import path from 'node:path'
import test from 'node:test'
import vm from 'node:vm'

import { assembleTavernClient } from '../bin/build-tavern-client.mjs'

test('客户端源码可确定性组装为唯一 DSH 运行产物', async () => {
  const first = await assembleTavernClient()
  const second = await assembleTavernClient()
  const committed = await readFile(new URL('../tavern-plugin/lib/client.js', import.meta.url), 'utf8')
  assert.equal(first, second)
  assert.equal(first, committed)
  assert.match(first, /^\/\/ Generated by pnpm build:client; do not edit directly\./)
  assert.doesNotMatch(first, /^\s*\/\/ @include /m)
})

test('完整客户端必须可解析，局部源码测试不能代替入口语法检查', async () => {
  const source = await assembleTavernClient()
  assert.doesNotThrow(() => new vm.Script(source, { filename: 'tavern-plugin/lib/client.js' }))
})

for (const check of [false, true]) {
  test(`客户端 ${check ? '--check' : 'build'} 拒绝非法语法且保留现有产物`, async t => {
    // private fork: keep isolated worktree fixtures without recursive cleanup.
    await mkdir(new URL('../.tmp/', import.meta.url), {recursive:true})
    const root = await realpath(await mkdtemp(publicJoin(publicTmpdir(), 'tavern-client-build-')))
    const builder = path.join(root, 'bin/build-tavern-client.mjs')
    const template = path.join(root, 'tavern-plugin/src/client/main.js')
    const output = path.join(root, 'tavern-plugin/lib/client.js')
    for (const directory of ['bin', 'tavern-plugin/src/client', 'tavern-plugin/lib/client-assets']) {
      await mkdir(path.join(root, directory), { recursive: true })
    }
    await copyFile(new URL('../bin/build-tavern-client.mjs', import.meta.url), builder)
    await cp(new URL('../tavern-plugin/packages/dsh-tavern-ui/', import.meta.url), path.join(root, 'tavern-plugin/packages/dsh-tavern-ui'), { recursive: true })
    // private fork: the fixture includes every required inert builder input.
    for (const name of ['fork-surfaces.cjs', ...['motion', 'phase', 'timing', 'script', 'player'].map(part => 'fork-skin-overlay-' + part + '.cjs')]) {
      await copyFile(new URL('../tavern-plugin/src/client/' + name, import.meta.url), path.join(root, 'tavern-plugin/src/client', name))
    }
    for (const name of ['tavern.css', 'fork-theme.css', 'fork-layered-sprite.css', 'fork-phone.css', 'fork-mod-config.css', 'fork-textcard.css']) await writeFile(path.join(root, 'tavern-plugin/lib/client-assets', name), '')
    await mkdir(path.join(root, 'tavern-plugin/shared'), { recursive: true })
    await writeFile(path.join(root, 'tavern-plugin/shared/keyword-catalogue.cjs'), 'module.exports = {};')
    for (const name of ['logo', 'lockup', 'lockup-dark']) await writeFile(path.join(root, `tavern-plugin/lib/client-assets/${name}.svg`), '<svg/>')
    const valid = 'const fixture = 1;\n'
    const invalid = 'const = 1;\n'
    await writeFile(template, valid)
    const build = args => spawnSync(process.execPath, [builder, ...args], { encoding: 'utf8', timeout: 10000 })
    const initial = build([])
    assert.ifError(initial.error)
    assert.equal(initial.status, 0, initial.stderr)
    let previous = await readFile(output, 'utf8')
    assert.ok(previous.includes(valid))
    // private fork: stale optional chunks must not be written before the main script is validated.
    const overlayPath = path.join(root, 'tavern-plugin/lib/client-assets/skin-overlay.mjs')
    const previousOverlay = await readFile(overlayPath, 'utf8')
    await writeFile(path.join(root, 'tavern-plugin/src/client/fork-skin-overlay-motion.cjs'), '\n// changed fixture\n', {flag:'a'})
    await writeFile(template, invalid)
    if (check) {
      // Keep source and output in sync so an outdated-output error cannot pass this test.
      previous = previous.replace(valid, invalid)
      await writeFile(output, previous)
    }
    const result = build(check ? ['--check'] : [])
    assert.ifError(result.error)
    assert.equal(result.status, 1, result.stdout + result.stderr)
    assert.match(result.stderr, /Unexpected token/)
    assert.equal(await readFile(output, 'utf8'), previous)
    assert.equal(await readFile(overlayPath, 'utf8'), previousOverlay)
  })
}

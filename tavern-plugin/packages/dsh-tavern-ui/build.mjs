import { readFile, writeFile, mkdir } from 'node:fs/promises'
import vm from 'node:vm'

const root = new URL('./', import.meta.url)
export async function assembleClient() {
  let source = await readFile(new URL('src/client.js', root), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
  for (const match of [...source.matchAll(/^([ \t]*)\/\/ @include ([\w-]+\.js)$/gm)].reverse()) {
    const fragment = await readFile(new URL('src/' + match[2], root), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
    source = source.slice(0, match.index) + fragment.trimEnd().split('\n').map(line => match[1] + line).join('\n') + source.slice(match.index + match[0].length)
  }
  const css = await readFile(new URL('src/shell.css', root), 'utf8').then(value => value.replace(/\r\n?/g, '\n'))
  const output = '// Generated by node bin/build-tavern-client.mjs; do not edit.\n' + source.replace('__SHELL_CSS__', () => JSON.stringify(css))
  new vm.Script(output)
  return output
}
export async function buildClient({ check = false, output } = {}) {
  output ??= await assembleClient()
  const target = new URL('lib/client.js', root)
  const current = await readFile(target, 'utf8').then(value => value.replace(/\r\n?/g, '\n')).catch(() => '')
  if (current === output) return
  if (check) throw new Error('Stale dsh-tavern-ui client; run node bin/build-tavern-client.mjs')
  await mkdir(new URL('lib/', root), { recursive: true })
  await writeFile(target, output)
}

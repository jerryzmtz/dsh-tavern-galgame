import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('.',import.meta.url))
const sourceFiles = new Set()
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
function emit(path, text) {
  if (process.argv.includes('--check')) { if (readFileSync(path,'utf8') !== text) throw new Error('Stale build: ' + path); return }
  mkdirSync(dirname(path),{recursive:true}); writeFileSync(path,text)
}
function visit(dir, relative = '') {
  for (const item of readdirSync(dir,{withFileTypes:true})) {
    const name = join(relative,item.name), path = join(dir,item.name)
    if (item.isDirectory()) visit(path,name)
    else {
      const source = readFileSync(path,'utf8')
      sourceFiles.add(name)
      emit(join(root,'lib',name), name === 'client.cjs' ? '// Generated by build.mjs; do not edit.\nwindow.__ModuleLoader__.load({id:' + JSON.stringify(manifest.name) + ',factory:(require)=>{const exports={};\n' + source + '\nreturn exports;}});\n' : source)
    }
  }
}
// Vendor only the inert P0 contracts so the asset package remains standalone.
// The protocol package is their sole maintained source; --check covers both copies.
for (const [source, target] of [
  ['voice-schema.js', 'shared/voice-schema.js'],
  ['asset-pack-json.js', 'shared/asset-pack-json.js'],
  ['asset-variant-table.cjs', 'shared/asset-variant-table.cjs'],
  ['asset-variants.js', 'shared/asset-variants.js'],
  ['asset-variant-content.js', 'shared/asset-variant-content.js'],
  ['stage-skin.cjs', 'shared/stage-skin.cjs'],
  ['skin-overlay.cjs', 'shared/skin-overlay.cjs'],
  ['../schema/skin.schema.json', 'schema/skin.schema.json'],
  ['../schema/atlas.schema.json', 'schema/atlas.schema.json'],
  ['../schema/glyphs.schema.json', 'schema/glyphs.schema.json'],
  ['asset-packs.js', 'shared/asset-pack-refs.js'],
  ['types/asset-packs.d.ts', 'asset-packs/protocol.d.ts']
]) {
  emit(join(root, 'src', target), (source.endsWith('.json') ? '' : '// Generated from dsh-presentation-protocol by build.mjs; do not edit.\n') + readFileSync(join(root, '../dsh-presentation-protocol/src', source), 'utf8').replaceAll("from './asset-packs.js'", "from './asset-pack-refs.js'"))
}
// The trusted performance mod owns this fixed kind; standalone packages vendor its inert contract.
emit(join(root, 'src/shared/audience.js'), '// Generated from dsh.danmaku by build.mjs; do not edit.\n' +
  readFileSync(join(root, '../../../fork/mods/danmaku/audience.js'), 'utf8'))
const performanceRoot = join(root, '../../../fork/mods/performance')
emit(join(root, 'src/shared/stage-performance.cjs'), '// Generated from dsh.performance by build.mjs; do not edit.\n' +
  readFileSync(join(performanceRoot, 'contract.cjs'), 'utf8')
    .replace("require('./schema/performance.schema.json')", "require('../schema/performance.schema.json')")
    .replaceAll('../../../tavern-plugin/packages/dsh-presentation-protocol/src/', './'))
emit(join(root, 'src/schema/performance.schema.json'), readFileSync(join(performanceRoot, 'schema/performance.schema.json'), 'utf8'))
// private fork: share built-in identities, never parser synonyms or implicit writer guidance.
// Variant labels are stored in pack declarations, never generated from a global table.
emit(join(root, 'src/shared/widget-theme.cjs'), '// Generated widget theme contract by build.mjs; do not edit.\n' + readFileSync(join(root, '../../src/client/fork-widget-theme.cjs'),'utf8'))
const moodSource = readFileSync(join(root, '../../src/client/fork-bubble-line.cjs'), 'utf8');
const moodStart = moodSource.indexOf('function forkResolveBubbleMood('), moodEnd = moodSource.indexOf('// private fork: the same exact resolver', moodStart);
emit(join(root, 'src/shared/emotion-identity.cjs'), '// Generated existing mood resolver by build.mjs; do not edit.\n' + moodSource.slice(moodStart, moodEnd) + 'module.exports = {forkResolveBubbleMood};\n');
const widgetSource = readFileSync(join(root, '../../src/client/fork-widget-contracts.cjs'), 'utf8')
const widgetBoundary = widgetSource.indexOf('function forkNormalizeWidgetTuning(')
if (widgetBoundary < 0) throw new Error('Missing widget schema extraction boundary')
emit(join(root, 'src/shared/widget-schema.cjs'), '// Generated widget schema subset by build.mjs; do not edit.\n' + widgetSource.slice(0, widgetBoundary) + 'module.exports = { forkWidgetSettingValue, forkValidateWidgetSettings, forkWidgetSettingsMap, forkValidateWidgetSettingValues, forkValidateWidgetSettingBindings, forkWidgetResolveSettings, forkWidgetSettingLabel, FORK_WIDGET_LIMITS, forkWidgetSchemaValid, forkWidgetSchemaValue, forkValidateWidgetDocument };\n')
// Remove generated files whose source was deleted; --check rejects stale surface too.
function prune(dir, relative = '') {
  for (const item of readdirSync(dir, {withFileTypes:true})) {
    const name = join(relative, item.name), target = join(dir, item.name)
    if (item.isDirectory()) prune(target, name)
    else if (!sourceFiles.has(name)) {
      if (process.argv.includes('--check')) throw new Error('Obsolete build: ' + target)
      rmSync(target)
    }
  }
}
visit(join(root,'src'))
prune(join(root, 'lib'))
